"""
UVA 10415 - Eb Alto Saxophone Player

題目中文意思：
薩克斯風每個音會按一些手指，計算整首歌每根手指從沒按到按下的次數。

這題需要什麼資料：
第一行測資數；每行一串音符。

解法重點：
用表格記每個音按哪些指頭，逐字比較前一狀態與現在狀態。

寫程式時可以照這個順序想：
1. 先把輸入讀進來，確認是一行一組、第一行有測資數，還是讀到 EOF。
2. 把題目要的規則轉成變數、迴圈、判斷式或函式。
3. 按照題目指定格式輸出，CPE/UVA 很常因為空格、空行、大小寫錯而 WA。
"""

# ===== 程式開始 =====
# 下面保留可以直接提交的 Python 解答。
# 註解會寫「這行在做什麼」以及「為什麼要這樣做」，
# 你用 Cursor 看時，可以先讀上面的題目說明，再對照下面程式。

# 匯入 sys：CPE/UVA 常用 sys.stdin 讀輸入，速度快，也能自然讀到 EOF。
import sys

notes = {
    "c": "0111001111", "d": "0111001110", "e": "0111001100", "f": "0111001000",
    "g": "0111000000", "a": "0110000000", "b": "0100000000",
    "C": "0010000000", "D": "1111001110", "E": "1111001100", "F": "1111001000",
    "G": "1111000000", "A": "1110000000", "B": "1100000000",
}
# splitlines() 逐行保留資料，適合每一行都有意義的題目。
lines = sys.stdin.read().splitlines()
t = int(lines[0])
# for 迴圈用來逐筆處理測資、逐格檢查，或跑完整個範圍。
for song in lines[1:1+t]:
    prev = "0000000000"
    ans = [0] * 10
    # for 迴圈用來逐筆處理測資、逐格檢查，或跑完整個範圍。
    for ch in song:
        cur = notes[ch]
        # for 迴圈用來逐筆處理測資、逐格檢查，或跑完整個範圍。
        for i in range(10):
            # if 判斷題目的特殊情況或規則分支。
            if prev[i] == "0" and cur[i] == "1":
                ans[i] += 1
        prev = cur
    # print 負責輸出答案；字串格式要完全符合題目，空格和大小寫都很重要。
    print(" ".join(map(str, ans)))
